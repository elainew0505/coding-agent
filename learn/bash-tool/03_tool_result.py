"""Step 3: turn the model's tool call into a tool result it can read.

No real API call: the model's response is a hard-coded list shaped like one.
Runs on the host with hard-coded, harmless commands only.
Run: python3 learn/bash-tool/03_tool_result.py
"""

import subprocess

MAX_OUTPUT_CHARS = 200  # tiny so we can see truncation; the real limit is much larger


def truncate(text: str, limit: int = MAX_OUTPUT_CHARS) -> str:
    """Keep the start and end of long output, and say how much was cut."""
    if len(text) <= limit:
        return text
    half = limit // 2
    cut = len(text) - limit
    # Head and tail, because errors and summaries usually appear at the end.
    return f"{text[:half]}\n... [{cut} characters cut] ...\n{text[-half:]}"


def handle_bash_call(tool_use: dict) -> dict:
    """Run the command from one tool_use block and build its tool_result block."""
    command = tool_use["input"]["command"]
    try:
        completed = subprocess.run(
            ["bash", "-c", command],
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
            timeout=5,
        )
    except subprocess.TimeoutExpired:
        # The tool itself failed: tell the model with is_error.
        return {
            "type": "tool_result",
            "tool_use_id": tool_use["id"],
            "content": "Command timed out after 5s",
            "is_error": True,
        }
    # A non-zero exit code is NOT a tool failure: the command ran and the model
    # should read its output and exit code, like you would in a terminal.
    text = truncate(completed.stdout) + f"\n[exit code: {completed.returncode}]"
    return {
        "type": "tool_result",
        "tool_use_id": tool_use["id"],  # links this result to the call the model made
        "content": text,
    }


# What the "content" of a model response might contain when it wants to use bash.
# The ids are generated by the API; "input" follows the bash tool's schema.
fake_model_content = [
    {"type": "text", "text": "Let me look around."},
    {"type": "tool_use", "id": "toolu_01", "name": "bash", "input": {"command": "echo hello"}},
    {"type": "tool_use", "id": "toolu_02", "name": "bash", "input": {"command": "seq 1 500"}},
    {"type": "tool_use", "id": "toolu_03", "name": "bash", "input": {"command": "cat missing.txt"}},
    {"type": "tool_use", "id": "toolu_04", "name": "bash", "input": {"command": "sleep 10"}},
]

# Every tool_use in one response gets a result, all in ONE user message.
results = []
for block in fake_model_content:
    if block["type"] == "tool_use" and block["name"] == "bash":
        results.append(handle_bash_call(block))
next_message = {"role": "user", "content": results}

for result in next_message["content"]:
    print(f"--- {result['tool_use_id']}  is_error={result.get('is_error', False)}")
    print(result["content"])
